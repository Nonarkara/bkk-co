import assert from 'node:assert/strict';
import{createRequire}from'node:module';
const M=createRequire(import.meta.url)('../public/footprint-model.js');
const square=(x=100,y=13,size=.001)=>[[[x,y],[x+size,y],[x+size,y+size],[x,y+size],[x,y]]];
const feature=(id,coordinates,type='Polygon')=>({type:'Feature',id,properties:{height:123},geometry:{type,coordinates}});
const place=(id,k,x=100.0005,y=13.0005)=>({id,k,x,y});
const a=square(),b=square(101),hole=square(100.0002,13.0002,.0006)[0];
const grouped=feature(77,[a,b],'MultiPolygon'),original=JSON.stringify(grouped);
const places=[place('c','cafe'),place('r','restaurant'),place('c2','cafe',100.0006),place('near','library',100.0011),place('wrong','bar')];
const input=JSON.stringify(places),idx=M.index(places),result=M.classify([grouped],idx);
assert.equal(result.features.length,1,'Grouped feature must not fill its unrelated component');
assert.equal(result.features[0].properties.mask,9,'Mixed categories are bit flags, never majority classification');
assert.deepEqual(result.features[0].properties.placeIDs,['c','r','c2']);
assert.equal(result.features[0].properties.tileFeatureID,77);
assert.equal(result.features[0].geometry.type,'Polygon');
assert.deepEqual(result.features[0].geometry.coordinates,a,'Every original source vertex is unchanged');
assert.equal(JSON.stringify(grouped),original);assert.equal(JSON.stringify(places),input);
result.features[0].geometry.coordinates[0][0][0]=999;
assert.equal(JSON.stringify(grouped),original,'Output coordinates cannot mutate the source');
const sameID=M.classify([feature(77,a),feature(77,b)],M.index([place('a','cafe'),place('b','library',101.0005)]));
assert.equal(sameID.features.length,2,'A shared tile feature ID does not merge disjoint buildings');
assert.deepEqual(sameID.features.map(f=>f.properties.mask),[1,4]);
assert.notEqual(sameID.features[0].id,sameID.features[1].id);
const duplicate=M.classify([grouped,grouped,feature(88,a)],idx);
assert.equal(duplicate.features.length,1,'Repeated identical geometry is deduplicated');
assert.deepEqual(duplicate.features[0].properties.placeIDs,['c','r','c2']);
const holed=feature('hole',[a[0],hole]);
assert.equal(M.classify([holed],M.index([place('inside-hole','cafe')])).features.length,0);
const boundaries=[place('edge','cafe',100,13.0005),place('corner','cafe',100,13),place('hole-edge','cafe',100.0002,13.0005)];
assert.equal(M.classify([holed],M.index(boundaries)).features.length,0,'Outer/hole boundaries and vertices stay unknown');
const aroundHole=M.classify([holed],M.index([place('outside-hole','coworking',100.0001,13.0005)]));
assert.equal(aroundHole.features[0].properties.mask,2);assert.deepEqual(aroundHole.features[0].geometry.coordinates,[a[0],hole]);
assert.equal(M.classify([feature('near',a)],M.index([place('outside','cafe',100.00101)])).features.length,0,'No nearest-footprint assignment');
const invalid=[place('bad','bar'),place('prototype','toString'),place('nan','cafe',NaN),place('infinity','library',100,Infinity),place('string','restaurant','100.0005'),{k:'cafe',x:100.0005,y:13.0005}];
assert.equal(M.index(invalid).bins.size,0,'Only known categories, exact IDs and finite numeric coordinates enter the index');
assert.equal(M.classify([feature('all',a)],M.index(['cafe','coworking','library','restaurant'].map((k,i)=>place(i,k)))).features[0].properties.mask,15);
const many=Array.from({length:2420},(_,i)=>square(100+(i%100)*.003,13+Math.floor(i/100)*.003));
const last=many.at(-1)[0][0],large=M.classify([feature(1,many,'MultiPolygon')],M.index([place('last','cafe',last[0]+.0005,last[1]+.0005)]));
assert.equal(large.features.length,1,'A 2420-component source aggregation colors only the actual containing component');
assert.deepEqual(large.features[0].geometry.coordinates,many.at(-1));
console.log('Footprint component containment, holes/boundaries, mixed masks, source preservation, deduplication and 2420-component aggregation pass.');
